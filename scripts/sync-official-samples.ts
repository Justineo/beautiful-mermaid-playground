import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import ts from "typescript";

const ROOT = process.cwd();
const SOURCE_URL =
  "https://raw.githubusercontent.com/lukilabs/beautiful-mermaid/main/samples-data.ts";
const OUTPUT_PATH = path.join(ROOT, "src/data/officialSamples.ts");

function toPrettyJson(value) {
  return JSON.stringify(value, null, 2);
}

async function writeIfChanged(filePath, content) {
  let previous = null;
  try {
    previous = await readFile(filePath, "utf8");
  } catch {
    previous = null;
  }

  if (previous === content) {
    return false;
  }

  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, content, "utf8");
  return true;
}

type SampleLiteral =
  | string
  | number
  | boolean
  | null
  | SampleLiteral[]
  | {
      [key: string]: SampleLiteral;
    };

function readLiteral(node: ts.Expression): SampleLiteral {
  if (ts.isStringLiteralLike(node)) return node.text;
  if (ts.isNumericLiteral(node)) return Number(node.text);
  if (
    ts.isPrefixUnaryExpression(node) &&
    node.operator === ts.SyntaxKind.MinusToken &&
    ts.isNumericLiteral(node.operand)
  )
    return -Number(node.operand.text);
  if (node.kind === ts.SyntaxKind.TrueKeyword) return true;
  if (node.kind === ts.SyntaxKind.FalseKeyword) return false;
  if (node.kind === ts.SyntaxKind.NullKeyword) return null;
  if (ts.isArrayLiteralExpression(node)) return node.elements.map(readLiteral);
  if (ts.isObjectLiteralExpression(node)) {
    return Object.fromEntries(
      node.properties.map((property) => {
        if (
          !ts.isPropertyAssignment(property) ||
          (!ts.isIdentifier(property.name) && !ts.isStringLiteral(property.name))
        ) {
          throw new Error("Expected a literal property in the official samples.");
        }
        return [property.name.text, readLiteral(property.initializer)];
      }),
    );
  }
  throw new Error(`Unsupported value in the official samples: ${ts.SyntaxKind[node.kind]}.`);
}

function extractSamples(source: string): SampleLiteral[] {
  // Read the same data as the upstream site generator without executing the downloaded module.
  const file = ts.createSourceFile("samples-data.ts", source, ts.ScriptTarget.Latest);
  if (
    "parseDiagnostics" in file &&
    Array.isArray(file.parseDiagnostics) &&
    file.parseDiagnostics.length > 0
  ) {
    throw new Error("Invalid TypeScript in the official samples source.");
  }
  const samples = file.statements
    .filter(ts.isVariableStatement)
    .flatMap((statement) => statement.declarationList.declarations)
    .find(({ name }) => ts.isIdentifier(name) && name.text === "samples")?.initializer;
  if (!samples || !ts.isArrayLiteralExpression(samples) || samples.elements.length === 0) {
    throw new Error("Expected a non-empty `samples` array in the official samples source.");
  }
  return samples.elements.map(readLiteral);
}

function isPlainObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function normalizeCategory(category) {
  if (category === "Hero") {
    return "Basic";
  }

  return category;
}

function normalizeTitle(title, category) {
  if (category === "Basic") {
    return "Basic";
  }

  return title;
}

function normalizeSource(source) {
  return source.replace(/\r\n?/gu, "\n");
}

function toOfficialSamples(samplesPayload) {
  if (!Array.isArray(samplesPayload)) {
    throw new Error("Invalid samples payload: expected an array.");
  }

  return samplesPayload.map((item, index) => {
    if (!isPlainObject(item)) {
      throw new Error(`Invalid sample at index ${index}: expected an object.`);
    }

    const titleRaw = typeof item.title === "string" ? item.title : "";
    const descriptionRaw = typeof item.description === "string" ? item.description : "";
    if (typeof item.source !== "string" || !item.source.trim()) {
      throw new Error(`Invalid sample at index ${index}: expected a Mermaid source string.`);
    }
    const categoryRaw = typeof item.category === "string" ? item.category : "Other";

    const category = normalizeCategory(categoryRaw);
    const options = isPlainObject(item.options) ? item.options : {};

    return {
      id: index,
      title: normalizeTitle(titleRaw, category),
      description: descriptionRaw,
      source: normalizeSource(item.source),
      category,
      options,
    };
  });
}

function getCategoryList(samples) {
  const categories = [];
  const seen = new Set();

  for (const sample of samples) {
    if (seen.has(sample.category)) {
      continue;
    }

    seen.add(sample.category);
    categories.push(sample.category);
  }

  if (!seen.has("Basic")) {
    categories.unshift("Basic");
  }

  return categories;
}

function renderOfficialSamplesFile(samples) {
  const categories = getCategoryList(samples);

  return `// Generated by scripts/sync-official-samples.ts. Do not edit manually.
export interface OfficialSample {
  id: number;
  title: string;
  description: string;
  source: string;
  category: string;
  options: Record<string, unknown>;
}

function trimSourceTrailingSpaces(source: string): string {
  return source
    .split("\\n")
    .map((line) => line.replace(/[ \\t]+$/u, ""))
    .join("\\n");
}

function normalizeSourceIndentation(source: string): string {
  return source
    .split("\\n")
    .map((line) => {
      const leadingWhitespaceMatch = line.match(/^[ \\t]+/u);
      if (!leadingWhitespaceMatch) {
        return line;
      }

      const normalizedLeadingWhitespace = leadingWhitespaceMatch[0]
        .replace(/\\t/gu, "  ")
        .replace(/ {4}/gu, "  ");
      return \`\${normalizedLeadingWhitespace}\${line.slice(leadingWhitespaceMatch[0].length)}\`;
    })
    .join("\\n");
}

export const OFFICIAL_SAMPLE_CATEGORIES: string[] = ${toPrettyJson(categories)};

const RAW_OFFICIAL_SAMPLES: OfficialSample[] = ${toPrettyJson(samples)};

export const OFFICIAL_SAMPLES: OfficialSample[] = RAW_OFFICIAL_SAMPLES.map((sample) => ({
  ...sample,
  source: normalizeSourceIndentation(trimSourceTrailingSpaces(sample.source)),
}));
`;
}

async function main() {
  const response = await fetch(SOURCE_URL, {
    headers: {
      "user-agent": "beautiful-mermaid-playground-sync-script",
    },
    signal: AbortSignal.timeout(15_000),
  });

  if (!response.ok) {
    throw new Error(`HTTP ${response.status} ${response.statusText} from ${response.url}.`);
  }

  const samples = toOfficialSamples(extractSamples(await response.text()));
  const output = renderOfficialSamplesFile(samples);

  const written = await writeIfChanged(OUTPUT_PATH, output);
  const verb = written ? "Updated" : "Up-to-date";
  console.log(`${verb} ${path.relative(ROOT, OUTPUT_PATH)} (${samples.length} samples)`);
}

main().catch((error) => {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`Failed to sync official samples from ${SOURCE_URL}: ${message}`);
  process.exitCode = 1;
});
